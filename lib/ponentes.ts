const FOTO_BY_NOMBRE = new Map(PONENTES.map(p => [p.nombre, p.foto]))

export function ponenteFoto(nombre: string): string | undefined {
  return FOTO_BY_NOMBRE.get(nombre)
}

export function ponenteIniciales(nombre: string): string {
  return nombre
    .replace('Dra. ', '')
    .replace('Dr. ', '')
    .split(' ')
    .slice(0, 2)
    .map(n => n[0])
    .join('')
}
